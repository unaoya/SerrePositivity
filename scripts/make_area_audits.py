"""Generate the per-area declaration audits in scripts/audit/.

Each generated file imports every tracked module of one area and checks, for every
declaration defined in those modules, that
  * no new `axiom` is declared,
  * no declaration uses `Lean.ofReduceBool` / `Lean.trustCompiler` (native_decide),
  * the only declarations containing `sorry` directly are the listed quotations.
Together with Mathlib this implies every declaration of the area depends only on
propext, Classical.choice, Quot.sound and the listed quotations.

Run from the repository root:  python3 scripts/make_area_audits.py
Then check an area with:        lake env lean scripts/audit/<area>.lean
"""
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AREAS = {
    "dg": (["DifferentialGraded", "Inputs/DifferentialGraded"], []),
    "clmst": (["CLMST"], []),
    "bhatt_scholze": (["BhattScholze"], [
        "SerrePositivity/BhattScholze/Inputs/Perfectoidization.lean",
        "SerrePositivity/BhattScholze/Inputs/ArcExcision.lean",
    ]),
    "adams": (["KTheory", "IntersectionMultiplicity"], []),
    "shared": (["HomologicalAlgebra", "CommutativeAlgebra", "PerfectComplex", "LengthAlgebra",
                "Asymptotic", "LinearAlgebra", "FieldTheory", "CategoryTheory", "GroupTheory",
                "Paper", "Inputs"], [
        "SerrePositivity/Paper/Section4/SupportedDescent.lean",
        "SerrePositivity/Inputs/Descent.lean",
        "SerrePositivity/Inputs/Homotopy/KanQuillen.lean",
    ]),
}
# Subdirectories of an area that belong to another area.
EXCLUDE = {"shared": ["Inputs/DifferentialGraded"]}

def tracked(dirs, exclude):
    out = subprocess.run(["git", "ls-files", "SerrePositivity"], cwd=ROOT,
                         capture_output=True, text=True, check=True).stdout.split()
    mods = []
    for f in out:
        if not f.endswith(".lean"):
            continue
        rel = f[len("SerrePositivity/"):]
        if any(rel == d + ".lean" or rel.startswith(d + "/") for d in dirs) and \
           not any(rel.startswith(e + "/") for e in exclude):
            mods.append("SerrePositivity." + rel[:-5].replace("/", "."))
    return sorted(mods)

TEMPLATE = '''/-
Generated by scripts/make_area_audits.py (area: {area}). Do not edit by hand.
For every declaration defined in the modules below, the axioms reported by Lean are among
propext, Classical.choice, Quot.sound and sorryAx (so no new axiom and no native_decide).
`sorry` / `admit` may be written only in the listed quotation files; this is checked on the
sources, because the bodies of imported theorems are not available to the elaborator.
Run from the repository root: lake env lean scripts/audit/{area}.lean
-/
{imports}

open Lean Elab Command in
run_cmd do
  let env ← getEnv
  let mods : Std.HashSet Name := Std.HashSet.ofList [{mods}]
  let allowedFiles : List String := [{allowed}]
  let std : List Name := [`propext, `Classical.choice, `Quot.sound, `sorryAx]
  let mut count : Nat := 0
  let mut withSorry : Nat := 0
  let mut bad : Array (Name × Array Name) := #[]
  for (c, _) in env.constants.map₁.toList do
    let some idx := env.getModuleIdxFor? c | continue
    unless mods.contains env.header.moduleNames[idx.toNat]! do continue
    count := count + 1
    let axs ← Lean.collectAxioms c
    if axs.contains `sorryAx then withSorry := withSorry + 1
    let extra := axs.filter (fun a => !std.contains a)
    unless extra.isEmpty do bad := bad.push (c, extra)
  let mut sorryFiles : Array String := #[]
  for m in mods.toList do
    let path := (m.toString.replace "." "/") ++ ".lean"
    let src ← IO.FS.readFile path
    -- drop comments and string literals before searching for the tokens
    let mut out := ""
    let mut depth := 0
    let mut i := 0
    let cs := src.toList.toArray
    while i < cs.size do
      if i + 1 < cs.size && cs[i]! == '/' && cs[i+1]! == '-' then
        depth := depth + 1; i := i + 2
      else if depth > 0 && i + 1 < cs.size && cs[i]! == '-' && cs[i+1]! == '/' then
        depth := depth - 1; i := i + 2
      else if depth == 0 && cs[i]! == '"' then
        i := i + 1
        while i < cs.size && cs[i]! != '"' do
          if cs[i]! == '\\\\' then i := i + 2 else i := i + 1
        i := i + 1
      else if depth == 0 && i + 1 < cs.size && cs[i]! == '-' && cs[i+1]! == '-' then
        while i < cs.size && cs[i]! != '\\n' do i := i + 1
      else
        if depth == 0 then out := out.push cs[i]!
        i := i + 1
    let mut found := false
    let mut word := ""
    for ch in (out.push ' ').toList do
      if ch.isAlphanum || ch == '_' || ch == '.' || ch == '\\'' then word := word.push ch
      else
        if word == "sorry" || word == "admit" then found := true
        word := ""
    if found && !allowedFiles.contains path then sorryFiles := sorryFiles.push path
  logInfo m!"{{count}} declarations in {{mods.size}} modules checked; {{withSorry}} depend on sorryAx through the allowed quotations"
  unless bad.isEmpty do logError m!"non-standard axioms: {{bad}}"
  unless sorryFiles.isEmpty do logError m!"sorry outside the allowed quotation files: {{sorryFiles}}"
'''

def main():
    for area, (dirs, allowed) in AREAS.items():
        mods = tracked(dirs, EXCLUDE.get(area, []))
        text = TEMPLATE.format(
            area=area,
            imports="\n".join("import " + m for m in mods),
            mods=", ".join("`" + m for m in mods),
            allowed=", ".join('"' + a + '"' for a in allowed))
        (ROOT / "scripts" / "audit" / f"{area}.lean").write_text(text)
        print(f"{area}: {len(mods)} modules")

if __name__ == "__main__":
    main()
