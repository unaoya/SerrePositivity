"""Approved R75 consumers versus unexpected imports; no source mutation."""
from pathlib import Path
import tempfile
import unittest
from check_r75 import importer_action

class ImporterTests(unittest.TestCase):
    def test_generated_area_requires_generator_marker(self):
        with tempfile.TemporaryDirectory() as d:
            root=Path(d);p=root/'scripts/audit/shared.lean';p.parent.mkdir(parents=True)
            p.write_text('/-\nGenerated by scripts/make_area_audits.py (area: shared). Do not edit by hand.\n-/\n')
            self.assertEqual(importer_action(root,'SerrePositivity.X','scripts/audit/shared.lean'),'regenerate_area_audit')
            p.write_text('import SerrePositivity.X\n')
            self.assertEqual(importer_action(root,'SerrePositivity.X','scripts/audit/shared.lean'),'STOP')
    def test_check_deletion_is_exact(self):
        p='scripts/check_word_source_operators.lean'
        self.assertEqual(importer_action(Path('.'),'SerrePositivity.CategoryTheory.Presentation.RetractWordPullback',p),'delete_check')
        self.assertEqual(importer_action(Path('.'),'SerrePositivity.Other',p),'STOP')
    def test_redirect_is_exact(self):
        p='SerrePositivity/Spectra/SymmetricSequence/SpherePowers.lean'
        self.assertTrue(importer_action(Path('.'),'SerrePositivity.Spectra.SymmetricSequence.AdjacentBraid',p).startswith('redirect_to_'))
        self.assertEqual(importer_action(Path('.'),'SerrePositivity.Spectra.SymmetricSequence.TensorPowers',p),'STOP')
    def test_unexpected_consumer_stops(self):
        self.assertEqual(importer_action(Path('.'),'SerrePositivity.CategoryTheory.AnchoredChain','SerrePositivity/Other.lean'),'STOP')

if __name__=='__main__':unittest.main()
