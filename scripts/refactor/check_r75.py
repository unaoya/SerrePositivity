#!/usr/bin/env python3
"""R75 §10.16: read-only inventory of 29 approved deletions and required repairs.
Eligible means all importers have an approved treatment, not that edits were applied.
Unexpected real importers STOP. Never deletes sources, regenerates audits or builds.
"""
from pathlib import Path
import argparse
import json
import re
import subprocess
import sys
import layer_check as lc


def importer_action(root, module, path):
    if path.startswith('scripts/audit/'):
        area=Path(path).stem
        marker='Generated by scripts/make_area_audits.py (area: '+area+'). Do not edit by hand.'
        if marker in (root/path).read_text().splitlines()[:3]:
            return 'regenerate_area_audit'
    if path=='scripts/check_word_source_operators.lean' and module=='SerrePositivity.CategoryTheory.Presentation.RetractWordPullback':
        return 'delete_check'
    if path=='SerrePositivity/Spectra/SymmetricSequence/SpherePowers.lean' and module=='SerrePositivity.Spectra.SymmetricSequence.AdjacentBraid':
        return 'redirect_to_SerrePositivity.CategoryTheory.Monoidal.AdjacentBraid'
    return 'STOP'


def inspect(r):
    paths=sorted((r/'SerrePositivity/CategoryTheory/Presentation').glob('*.lean'))
    paths += [r/('SerrePositivity/CategoryTheory/'+n+'.lean') for n in ['Quiver/WeightedPaths','Quiver/WeightedPathMaps','AnchoredChain','AnchoredChainContraction','AnchoredChainNerve','AnchoredChainSimplicial','AnchoredChainTransport','ArrowContext','LabelledChain','SimplexChainParameter']]
    paths += [r/('SerrePositivity/Spectra/SymmetricSequence/'+n+'.lean') for n in ['TensorPowers','TensorPermutations','AdjacentTranspositions','AdjacentBraid']]
    assert len(paths)==29 and all(p.exists() for p in paths)
    rows=[{'path':str(p.relative_to(r)),'module':str(p.relative_to(r)).removesuffix('.lean').replace('/','.'),'importers':[],'references':[],'readme_name_mentions':[]} for p in paths]
    byname={v['module']:v for v in rows}
    files=subprocess.check_output(['git','ls-files','-z'],cwd=r).decode().split('\0')
    for name in files:
     if not name:continue
     p=r/name
     if p.suffix not in ('.lean','.md','.json','.py','.sh','.txt'):continue
     text=p.read_text(errors='replace')
     if p.suffix=='.lean':
      # No need to mask every source in the repository if no target string occurs.
      found=[m for m in byname if m in text]
      if found:
       deps=lc.imports(text)
       for m in set(found)&deps:byname[m]['importers'].append(name)
     for row in rows:
      if name==row['path']:continue
      needles=[row['module'],row['path'],row['path'][len('SerrePositivity/'):],row['path'].removesuffix('.lean'),row['path'][len('SerrePositivity/'):].removesuffix('.lean')]
      if 'README' in p.name:
       leaf=Path(row['path']).stem
       for n,line in enumerate(text.splitlines(),1):
        if re.search(r'(?<![\w])'+re.escape(leaf)+r'(?![\w])',line):
         row['readme_name_mentions'].append({'path':name,'line':n,'text':line[:500]})
       for n,line in enumerate(text.splitlines(),1):
        links=re.findall(r'\]\(([^)#]+)(?:#[^)]*)?\)',line)
        if any((p.parent/link).resolve()==(r/row['path']).resolve() for link in links if '://' not in link):
         row['references'].append({'path':name,'line':n,'text':line[:500]})
      for n,line in enumerate(text.splitlines(),1) if any(x in text for x in needles) else []:
       if any(re.search(re.escape(x)+r'(?![\w./])',line) for x in needles):
        row['references'].append({'path':name,'line':n,'text':line[:500]})
    for row in rows:
     row['active_references']=[ref for ref in row['references'] if (ref['path'].startswith('scripts/') and not ref['path'].startswith('scripts/refactor/')) or 'README' in Path(ref['path']).name or ref['path'].endswith('.lean')]
     row['ready_without_edits']=not(row['importers'] or row['active_references'])
     row['importer_actions']=[{'path':name,'action':importer_action(r,row['module'],name)} for name in row['importers']]
     row['blocking_importers']=[x['path'] for x in row['importer_actions'] if x['action']=='STOP']
     row['approved_for_bundle']=True
     row['eligible']=not row['blocking_importers']
     row['reference_action']='§10.16: regenerate generated audits; remove obsolete module names from audits/manifest/checks; redirect qualified README paths; retain short declaration names'
    result={'source_base':subprocess.check_output(['git','rev-parse','HEAD'],cwd=r,text=True).strip(),'policy':'IF-W0-3 §10.16','status':'STOP' if any(x['blocking_importers'] for x in rows) else 'PASS','applied':False,'extra_delete':['scripts/check_word_source_operators.lean'],'candidates':29,'approved':29,'ready_without_edits':sum(x['ready_without_edits'] for x in rows),'eligible':sum(x['eligible'] for x in rows),'excluded':sum(not x['eligible'] for x in rows),'rows':rows}
    return result


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[2])
    parser.add_argument('--output',type=Path)
    args=parser.parse_args()
    result=inspect(args.root.resolve())
    text=json.dumps(result,ensure_ascii=False,indent=2)+'\n'
    if args.output:args.output.write_text(text)
    print(json.dumps({k:v for k,v in result.items() if k!='rows'},ensure_ascii=False))
    return int(result['status']!='PASS')

if __name__=='__main__':sys.exit(main())
